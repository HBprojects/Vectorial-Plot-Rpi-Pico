SCALE_FACTOR = 0.000435
TARGET_POINTS = 680

def interpolate_signal(original_data, target_size):
    """
    Increases the resolution of the signal using linear interpolation.
    """
    n = len(original_data)
    interpolated = []
    
    for i in range(target_size):
        # Calculate the relative position in the original array
        # 490 / 735 = 0.666...
        float_index = i * (n - 1) / (target_size - 1)
        index = int(float_index)
        fraction = float_index - index
        
        if index >= n - 1:
            interpolated.append(original_data[n-1])
        else:
            # Interpolate both Wave 0 and Wave 1
            p1 = original_data[index]
            p2 = original_data[index + 1]
            
            # Formula: p1 + (p2 - p1) * fraction
            w0 = p1[0] + (p2[0] - p1[0]) * fraction
            w1 = p1[1] + (p2[1] - p1[1]) * fraction
            interpolated.append((w0, w1))
            
    return interpolated

def run_signal_transmission():
    # Generate the 735 points version
    print("Resampling signal to 735 points...")
    signal_735 = interpolate_signal(ECG_SIGNAL1, TARGET_POINTS)
    print("Starting transmission...")

    while True:
        for row in signal_735:
            # Row[0] and Row[1] are now floats from interpolation
            wave0 = row[0] * SCALE_FACTOR
            wave1_raw = row[1] * SCALE_FACTOR
            
            wave2 = wave1_raw - wave0
            wave1 = wave1_raw * -1

            # Output 5 decimal values
            print("{:.5f}, {:.5f}, {:.5f}".format(wave0, wave1, wave2))

            # Adjusted delay: 
            # If you want the wave to last the same total time as before:
            # (490 pts * 32ms) / 735 pts = ~21ms
            utime.sleep_ms(5)

if __name__ == "__main__":
    run_signal_transmission()